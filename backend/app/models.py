"""
ORM models. Course content generated by the LLM (explanations, examples,
quiz questions) is stored as JSON text columns so the schema stays stable
even though the LLM's structured output can vary in shape/length.
"""
import datetime
from sqlalchemy import (
    Column, Integer, String, Text, ForeignKey, DateTime, Float, Boolean
)
from sqlalchemy.orm import relationship
from app.database import Base


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, nullable=False)
    email = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    courses = relationship("Course", back_populates="owner", cascade="all, delete-orphan")


class Course(Base):
    __tablename__ = "courses"

    id = Column(Integer, primary_key=True, index=True)
    owner_id = Column(Integer, ForeignKey("users.id"), nullable=False)

    topic = Column(String, nullable=False)
    difficulty = Column(String, nullable=False)       # beginner | intermediate | advanced
    duration = Column(String, nullable=False)         # e.g. "2 weeks", "10 hours"
    learning_goal = Column(String, nullable=True)      # free-text goal from the user

    title = Column(String, nullable=True)              # AI-generated
    description = Column(Text, nullable=True)          # AI-generated
    status = Column(String, default="generating")       # generating | ready | completed
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    owner = relationship("User", back_populates="courses")
    modules = relationship("Module", back_populates="course",
                            cascade="all, delete-orphan", order_by="Module.order_index")


class Module(Base):
    __tablename__ = "modules"

    id = Column(Integer, primary_key=True, index=True)
    course_id = Column(Integer, ForeignKey("courses.id"), nullable=False)

    order_index = Column(Integer, nullable=False)
    title = Column(String, nullable=False)
    subtopics_json = Column(Text, nullable=True)      # list of subtopic strings (outline stage)
    objectives_json = Column(Text, nullable=True)      # list of learning objectives

    content_md = Column(Text, nullable=True)            # generated explanation (markdown)
    examples_json = Column(Text, nullable=True)         # real-world + code examples
    is_generated = Column(Boolean, default=False)        # lazy content generation flag

    course = relationship("Course", back_populates="modules")
    assessments = relationship("Assessment", back_populates="module", cascade="all, delete-orphan")


class Assessment(Base):
    __tablename__ = "assessments"

    id = Column(Integer, primary_key=True, index=True)
    module_id = Column(Integer, ForeignKey("modules.id"), nullable=False)

    type = Column(String, nullable=False)   # "quiz" | "assignment"
    payload_json = Column(Text, nullable=False)  # questions/options/answers or assignment prompt

    module = relationship("Module", back_populates="assessments")


class QuizAttempt(Base):
    __tablename__ = "quiz_attempts"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    assessment_id = Column(Integer, ForeignKey("assessments.id"), nullable=False)
    module_id = Column(Integer, ForeignKey("modules.id"), nullable=False)

    score = Column(Float, nullable=False)         # 0-100
    answers_json = Column(Text, nullable=False)
    attempted_at = Column(DateTime, default=datetime.datetime.utcnow)


class ModuleProgress(Base):
    """Tracks whether a learner has completed a module (separate from quiz score)."""
    __tablename__ = "module_progress"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    module_id = Column(Integer, ForeignKey("modules.id"), nullable=False)
    completed = Column(Boolean, default=False)
    completed_at = Column(DateTime, nullable=True)


class TutorMessage(Base):
    __tablename__ = "tutor_messages"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    course_id = Column(Integer, ForeignKey("courses.id"), nullable=False)
    role = Column(String, nullable=False)     # "user" | "assistant"
    content = Column(Text, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)
